#!/usr/bin/env python3
"""The HUD's fonts as WOFF2 (+ licences) for the web port.

    <venv>/bin/python web/tools/convert_fonts.py        (needs fonttools + brotli)

AFuryHUD::BuildFont loads ten faces from FourthAndFury/Content/Fonts (FaceFiles in FuryHUD.cpp, one per
EFuryFace). The eight Barlow Condensed faces are drawn by the HUD; Anton and Graduate are registered but no
HUD code draws with EFuryFace::Anton / ::Graduate. They are converted too (small) so the faces map 1:1.
Writes web/public/assets/fonts/hud/*.woff2, the OFL texts, and fonts.css with one @font-face per EFuryFace.
"""
import os
import shutil

from fontTools.ttLib import TTFont

HERE = os.path.dirname(os.path.abspath(__file__))
REPO = os.path.abspath(os.path.join(HERE, "..", ".."))
SRC = os.path.join(REPO, "FourthAndFury", "Content", "Fonts")
DST = os.path.join(REPO, "web", "public", "assets", "fonts", "hud")   # web/src/hud/fonts.ts loads fonts/hud/<file>.woff2

# EFuryFace -> (file, CSS family, weight, style, used by the HUD)
FACES = [
    ("Medium", "BarlowCondensed-Medium.ttf", "Barlow Condensed", 500, "normal", True),
    ("SemiBold", "BarlowCondensed-SemiBold.ttf", "Barlow Condensed", 600, "normal", True),
    ("Bold", "BarlowCondensed-Bold.ttf", "Barlow Condensed", 700, "normal", True),
    ("ExtraBold", "BarlowCondensed-ExtraBold.ttf", "Barlow Condensed", 800, "normal", True),
    ("Black", "BarlowCondensed-Black.ttf", "Barlow Condensed", 900, "normal", True),
    ("BoldItalic", "BarlowCondensed-BoldItalic.ttf", "Barlow Condensed", 700, "italic", True),
    ("ExtraBoldItalic", "BarlowCondensed-ExtraBoldItalic.ttf", "Barlow Condensed", 800, "italic", True),
    ("BlackItalic", "BarlowCondensed-BlackItalic.ttf", "Barlow Condensed", 900, "italic", True),
    ("Anton", "Anton-Regular.ttf", "Anton", 400, "normal", False),
    ("Graduate", "Graduate-Regular.ttf", "Graduate", 400, "normal", False),
]


def main():
    os.makedirs(DST, exist_ok=True)
    css = ["/* 4th & Fury HUD faces (EFuryFace in FuryHUD.h). Generated by web/tools/convert_fonts.py. */"]
    for face, ttf, family, weight, style, used in FACES:
        font = TTFont(os.path.join(SRC, ttf))
        font.flavor = "woff2"
        out = os.path.splitext(ttf)[0] + ".woff2"
        font.save(os.path.join(DST, out))
        print("  %-38s %6.1f KB%s" % (out, os.path.getsize(os.path.join(DST, out)) / 1024, "" if used else "  (registered, unused by HUD)"))
        css.append("/* EFuryFace::%s%s */\n@font-face { font-family: '%s'; src: url('./%s') format('woff2'); "
                   "font-weight: %d; font-style: %s; font-display: block; }" % (face, "" if used else " (not drawn by the HUD)",
                                                                                family, out, weight, style))
    for lic in ("OFL-BarlowCondensed.txt", "OFL-Anton.txt", "OFL-Graduate.txt"):
        shutil.copy(os.path.join(SRC, lic), os.path.join(DST, lic))
    with open(os.path.join(DST, "fonts.css"), "w") as handle:
        handle.write("\n".join(css) + "\n")


if __name__ == "__main__":
    main()
